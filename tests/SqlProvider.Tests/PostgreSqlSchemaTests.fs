module PostgreSqlSchemaTests

// Schema-reading tests against a live PostgreSQL (11 or newer: the call test makes procedures).
// Set SQLPROVIDER_POSTGRES_TEST_CONNECTION to an Npgsql connection string of a scratch database
// where the tests may create and drop schemas; without it the tests are ignored.

open System
open System.Data
open FSharp.Data.Sql
open FSharp.Data.Sql.Common
open FSharp.Data.Sql.Schema
open NUnit.Framework

let private connectionString () =
#if NETFRAMEWORK
    // Npgsql through the dynamic provider does not complete in the net48 test host
    Assert.Ignore "PostgreSQL schema tests run on .NET only"
#endif
    match Environment.GetEnvironmentVariable "SQLPROVIDER_POSTGRES_TEST_CONNECTION" with
    | null | "" -> Assert.Ignore "SQLPROVIDER_POSTGRES_TEST_CONNECTION is not set"; ""
    | cs -> cs

let private createProvider () =
    let providerType = typeof<FSharp.Data.Sql.Runtime.SqlDataContext>.Assembly.GetType("FSharp.Data.Sql.Providers.PostgresqlProvider", true)
    let resolutionPath = AppContext.BaseDirectory
    Activator.CreateInstance(providerType, Reflection.BindingFlags.Instance ||| Reflection.BindingFlags.Public ||| Reflection.BindingFlags.NonPublic, null,
                             [| box resolutionPath; box ""; box "public"; box Array.empty<string> |], null) :?> ISqlProvider

// the provider's schema reads close the connection when they finish
let private execute (con:IDbConnection) (sql:string) =
    if con.State <> ConnectionState.Open then con.Open()
    use cmd = con.CreateCommand()
    cmd.CommandText <- sql
    cmd.ExecuteNonQuery() |> ignore

// It runs ADO.NET commands directly, which publish no SQL events
[<Test; SqlCheck.NoSql>]
let ``identity columns are autonumber and left out of the required columns``() =
    let cs = connectionString ()
    let provider = createProvider ()
    let schema = "sqlprovider_identity_" + Guid.NewGuid().ToString("N").Substring(0, 8)
    use con = provider.CreateConnection cs
    con.Open()
    provider.CreateTypeMappings con
    try
        execute con $"CREATE SCHEMA {schema}"
        execute con $"""CREATE TABLE {schema}.enrolment (
                            id uuid PRIMARY KEY,
                            number bigint GENERATED ALWAYS AS IDENTITY (START WITH 1000),
                            alt_number integer GENERATED BY DEFAULT AS IDENTITY,
                            member_sub text NOT NULL,
                            note text NULL)"""
        let columns = provider.GetColumns(con, { Schema = schema; Name = "enrolment"; Type = "BASE TABLE" })
        Assert.IsTrue(columns.["number"].IsAutonumber, "GENERATED ALWAYS AS IDENTITY")
        Assert.IsTrue(columns.["alt_number"].IsAutonumber, "GENERATED BY DEFAULT AS IDENTITY")
        Assert.IsFalse(columns.["member_sub"].IsAutonumber, "plain column")
        // the typed Create(...) takes the columns that are not nullable, autonumber or computed
        let required =
            columns |> Map.toList |> List.map snd
            |> List.filter (fun c -> not (c.IsNullable || c.IsAutonumber || c.IsComputed))
            |> List.map (fun c -> c.Name)
        Assert.AreEqual(["member_sub"], required)
    finally
        execute con $"DROP SCHEMA IF EXISTS {schema} CASCADE"

// A function call joins an open TransactionScope: the connection enlisted in it, so the call begins no transaction of
// its own (Npgsql refuses a second one), and the scope decides whether the call's work stays.
[<Test; SqlCheck.NoSql>]
let ``a function called inside a TransactionScope runs in that transaction``() =
    let cs = connectionString ()
    let provider = createProvider ()
    let schema = "sqlprovider_sproc_" + Guid.NewGuid().ToString("N").Substring(0, 8)
    use setup = provider.CreateConnection cs
    setup.Open()
    provider.CreateTypeMappings setup
    let marks () =
        if setup.State <> ConnectionState.Open then setup.Open()
        use count = setup.CreateCommand()
        count.CommandText <- $"SELECT count(*) FROM {schema}.mark"
        count.ExecuteScalar() |> Convert.ToInt64
    try
        execute setup $"CREATE SCHEMA {schema}"
        execute setup $"CREATE TABLE {schema}.mark (id int)"
        execute setup $"CREATE FUNCTION {schema}.add_mark() RETURNS void LANGUAGE sql AS $$ INSERT INTO {schema}.mark VALUES (1) $$"
        let call complete =
            use scope = new Transactions.TransactionScope(Transactions.TransactionScopeAsyncFlowOption.Enabled)
            use con = provider.CreateConnection cs
            con.Open()
            use com = provider.CreateCommand(con, $"SELECT {schema}.add_mark()")
            provider.ExecuteSprocCommand(com, [||], [||], [||]) |> ignore
            if complete then scope.Complete()
        call false
        Assert.AreEqual(0L, marks (), "rolled back with the scope")
        call true
        Assert.AreEqual(1L, marks (), "committed with the scope")
        // Async too
        (task {
            use scope = new Transactions.TransactionScope(Transactions.TransactionScopeAsyncFlowOption.Enabled)
            use con = provider.CreateConnection cs :?> Data.Common.DbConnection
            do! con.OpenAsync()
            use com = provider.CreateCommand(con, $"SELECT {schema}.add_mark()") :?> Data.Common.DbCommand
            let! _ = provider.ExecuteSprocCommandAsync(com, [||], [||], [||])
            scope.Complete()
        }).Wait()
        Assert.AreEqual(2L, marks (), "the async call committed with the scope")

        // A refcursor lives only inside a transaction. A connection that isn't enlisted in the scope (Enlist=false) isn't
        // in the scope's, so the call begins its own; an enlisted one reads the cursor in the scope's.
        execute setup $"CREATE FUNCTION {schema}.marks() RETURNS refcursor LANGUAGE plpgsql AS $$ DECLARE c refcursor; BEGIN OPEN c FOR SELECT id FROM {schema}.mark; RETURN c; END $$"
        let cursor =
            QueryParameter.Create(
                "ReturnValue", 0,
                TypeMapping.Create(clrType = typeof<SqlEntity[]>.ToString(), dbType = DbType.Object, providerTypeName = "refcursor", providerType = 23),
                ParameterDirection.ReturnValue)
        let readMarks (connection: string) =
            use scope = new Transactions.TransactionScope(Transactions.TransactionScopeAsyncFlowOption.Enabled)
            use con = provider.CreateConnection connection
            con.Open()
            use com = provider.CreateCommand(con, $"SELECT {schema}.marks()")
            match provider.ExecuteSprocCommand(com, [||], [| cursor |], [||]) with
            | SingleResultSet(_, rows) -> Seq.length rows
            | other -> failwithf "Expected the cursor's rows, got %A" other
        Assert.AreEqual(2, readMarks (cs + ";Enlist=false"), "outside the scope's transaction")
        Assert.AreEqual(2, readMarks cs, "inside the scope's transaction")
    finally
        execute setup $"DROP SCHEMA IF EXISTS {schema} CASCADE"

// The call a provided ctx.Functions.X.Invoke or ctx.Procedures.X.Invoke makes, through the data context: the routine by
// its schema and name (the schema isn't on the search path), a function inside a SELECT and a procedure with CALL, in
// the scope's transaction.
[<Test; SqlCheck.ExpectSql("EXEC")>]
let ``a function and a procedure outside the search path are called by schema and name``() =
    let cs = connectionString ()
    let provider = createProvider ()
    let schema = "sqlprovider_call_" + Guid.NewGuid().ToString("N").Substring(0, 8)
    use setup = provider.CreateConnection cs
    setup.Open()
    let marks () =
        if setup.State <> ConnectionState.Open then setup.Open()
        use read = setup.CreateCommand()
        read.CommandText <- $"SELECT coalesce(string_agg(id::text, ',' ORDER BY id), '') FROM {schema}.mark"
        read.ExecuteScalar() |> string
    try
        execute setup $"CREATE SCHEMA {schema}"
        execute setup $"CREATE TABLE {schema}.mark (id int)"
        execute setup $"CREATE FUNCTION {schema}.add_mark(mark integer) RETURNS void LANGUAGE sql AS $$ INSERT INTO {schema}.mark VALUES (mark) $$"
        execute setup $"CREATE FUNCTION {schema}.sum_marks(mark integer, integer) RETURNS integer LANGUAGE sql AS $$ SELECT $1 + $2 $$"
        execute setup $"CREATE PROCEDURE {schema}.put_mark(mark integer) LANGUAGE sql AS $$ INSERT INTO {schema}.mark VALUES (mark) $$"
        execute setup $"CREATE FUNCTION {schema}.marks_from(lowest integer) RETURNS TABLE (id integer) LANGUAGE sql AS $$ SELECT id FROM {schema}.mark WHERE id >= lowest $$"
        execute setup $"CREATE FUNCTION {schema}.mark_cursor() RETURNS refcursor LANGUAGE plpgsql AS $$ DECLARE c refcursor; BEGIN OPEN c FOR SELECT id FROM {schema}.mark; RETURN c; END $$"
        execute setup $"CREATE PROCEDURE {schema}.double_mark(step integer, INOUT mark integer) LANGUAGE plpgsql AS $$ BEGIN mark := mark * 2 + step; END $$"
        execute setup $"CREATE FUNCTION {schema}.mark_cursor_from(lowest integer) RETURNS refcursor LANGUAGE plpgsql AS $$ DECLARE c refcursor; BEGIN OPEN c FOR SELECT id FROM {schema}.mark WHERE id >= lowest; RETURN c; END $$"

        // Procedures are listed apart from the functions
        let listed kind =
            provider.GetSprocs setup
            |> List.choose (function
                | Root(root, Sproc routine) when root = kind && routine.Name.Owner = schema -> Some routine.Name.ProcName
                | _ -> None)
            |> List.sort
        CollectionAssert.AreEqual([ "add_mark"; "mark_cursor"; "mark_cursor_from"; "marks_from"; "sum_marks" ], listed "Functions")
        CollectionAssert.AreEqual([ "double_mark"; "put_mark" ], listed "Procedures")
        let context =
            FSharp.Data.Sql.Runtime.SqlDataContext(
                "PostgreSqlCall_" + schema, cs, DatabaseProviderTypes.POSTGRESQL, AppContext.BaseDirectory, [||],
                typeof<FSharp.Data.Sql.Runtime.SqlDataContext>.Assembly.Location, schema, CaseSensitivityChange.ORIGINAL, "", "",
                OdbcQuoteCharacter.DEFAULT_QUOTE, SQLiteLibrary.AutoSelect, Transactions.TransactionOptions.Default, None,
                SelectOperations.DotNetSide, "", false)
            :> ISqlDataContext
        let integer = TypeMapping.Create(clrType = typeof<int>.ToString(), dbType = DbType.Int32, providerTypeName = "integer", providerType = 9)
        let input name ordinal = QueryParameter.Create(name, ordinal, integer, ParameterDirection.Input)
        let routine name parameters : RunTimeSprocDefinition =
            { Name = { ProcName = name; Owner = schema; PackageName = "" }; Params = parameters }
        let addMark = routine "add_mark" [ input "mark" 0 ]
        let putMark = routine "put_mark" [ input "mark" 0 ]
        // The second parameter has no name: the provider names it by its place
        let sumMarks = routine "sum_marks" [ input "mark" 0; input "param1" 1 ]
        let returned = [| QueryParameter.Create("ReturnValue", 0, integer, ParameterDirection.ReturnValue) |]

        context.CallSproc(addMark, [||], [| box 1 |]) |> ignore
        context.CallSproc(putMark, [||], [| box 2 |]) |> ignore
        Assert.AreEqual("1,2", marks (), "a function and a procedure, each on its own")
        let sum = context.CallSproc(sumMarks, returned, [| box 3; box 4 |]) :?> SqlEntity
        Assert.AreEqual(7, (sum :> IColumnHolder).GetColumn<int> "ReturnValue", "a function's value, with a parameter that has no name")

        let inScope complete =
            use scope = new Transactions.TransactionScope(Transactions.TransactionScopeAsyncFlowOption.Enabled)
            context.CallSproc(addMark, [||], [| box 3 |]) |> ignore
            context.CallSproc(putMark, [||], [| box 4 |]) |> ignore
            if complete then scope.Complete()
        inScope false
        Assert.AreEqual("1,2", marks (), "rolled back with the scope")
        inScope true
        Assert.AreEqual("1,2,3,4", marks (), "committed with the scope")

        (task {
            let! _ = context.CallSprocAsync(addMark, [||], [| box 5 |])
            let! _ = context.CallSprocAsync(putMark, [||], [| box 6 |])
            let! sum = context.CallSprocAsync(sumMarks, returned, [| box 5; box 6 |])
            Assert.AreEqual(11, (sum :> IColumnHolder).GetColumn<int> "ReturnValue", "async")
        }).Wait()
        Assert.AreEqual("1,2,3,4,5,6", marks (), "async")

        // Rows: a function that returns a table, and one that returns a cursor
        let rowsOf (result: obj) = (result :?> SqlEntity :> IColumnHolder).GetColumn<SqlEntity[]> "ReturnValue" |> Array.length
        let rows typeName providerType =
            [| QueryParameter.Create(
                   "ReturnValue", -1,
                   TypeMapping.Create(clrType = typeof<SqlEntity[]>.ToString(), dbType = DbType.Object, providerTypeName = typeName, providerType = providerType),
                   ParameterDirection.ReturnValue) |]
        Assert.AreEqual(3, context.CallSproc(routine "marks_from" [ input "lowest" 0 ], rows "record" 23, [| box 4 |]) |> rowsOf, "a table")
        Assert.AreEqual(6, context.CallSproc(routine "mark_cursor" [], rows "refcursor" 23, [||]) |> rowsOf, "a cursor")
        Assert.AreEqual(2, context.CallSproc(routine "mark_cursor_from" [ input "lowest" 0 ], rows "refcursor" 23, [| box 5 |]) |> rowsOf, "a cursor of a function with a parameter")

        // A procedure's InputOutput parameter takes its value in and gives its result
        let inOut = QueryParameter.Create("mark", 1, integer, ParameterDirection.InputOutput)
        let doubled = context.CallSproc(routine "double_mark" [ input "step" 0; inOut ], [| inOut |], [| box 1; box 20 |]) :?> SqlEntity
        Assert.AreEqual(41, (doubled :> IColumnHolder).GetColumn<int> "mark", "an InputOutput parameter")
    finally
        execute setup $"DROP SCHEMA IF EXISTS {schema} CASCADE"

// Seq.lockForUpdate's FOR UPDATE: the query's rows stay locked until the transaction ends, so another transaction can't lock them.
[<Test; SqlCheck.NoSql>]
let ``FOR UPDATE locks the rows a query reads until the transaction ends``() =
    let cs = connectionString ()
    let provider = createProvider ()
    let schema = "sqlprovider_lock_" + Guid.NewGuid().ToString("N").Substring(0, 8)
    use setup = provider.CreateConnection cs
    setup.Open()
    provider.CreateTypeMappings setup
    try
        execute setup $"CREATE SCHEMA {schema}"
        execute setup $"CREATE TABLE {schema}.mark (id int PRIMARY KEY)"
        execute setup $"INSERT INTO {schema}.mark VALUES (1)"
        let table = { Schema = schema; Name = "mark"; Type = "" }
        let query = { SqlQuery.Empty with UltimateChild = Some("m", table); ForUpdate = true }
        let text (q: SqlQuery) = fst (provider.GenerateQueryText(q, "m", table, Collections.Generic.Dictionary(), false, setup))
        StringAssert.EndsWith(" FOR UPDATE", (text query).TrimEnd())
        StringAssert.EndsWith(" LIMIT 1 FOR UPDATE;", (text { query with Take = ValueSome 1 }).TrimEnd())

        // The nullable side of an outer join can't be locked, so with one the other tables are named
        execute setup $"CREATE TABLE {schema}.child (id int PRIMARY KEY, mark_id int)"
        let child = { Schema = schema; Name = "child"; Type = "" }
        let joined (outer: bool) =
            let link =
                { PrimaryTable = table
                  PrimaryKey = [ KeyColumn "id" ]
                  ForeignTable = child
                  ForeignKey = [ KeyColumn "mark_id" ]
                  OuterJoin = outer
                  IsNullableOuter = outer
                  RelDirection = RelationshipDirection.Children }
            text { query with Aliases = Map.ofList [ "c", child ]; Links = [ "m", link, "c" ] }
        StringAssert.EndsWith(" FOR UPDATE", (joined false).TrimEnd())
        StringAssert.EndsWith(" FOR UPDATE OF \"m\"", (joined true).TrimEnd())
        for sql in [ joined false; joined true ] do
            if setup.State <> ConnectionState.Open then setup.Open()
            use run = setup.CreateCommand()
            run.CommandText <- sql
            run.ExecuteScalar() |> ignore
        do
            use scope = new Transactions.TransactionScope(Transactions.TransactionScopeAsyncFlowOption.Enabled)
            use con = provider.CreateConnection cs
            con.Open()
            use locking = con.CreateCommand()
            locking.CommandText <- text query
            locking.ExecuteScalar() |> ignore
            // Another transaction waits for the lock, here at most a tenth of a second
            use other = provider.CreateConnection(cs + ";Enlist=false")
            other.Open()
            use waiting = other.CreateCommand()
            waiting.CommandText <- $"SET lock_timeout = '100ms'; SELECT id FROM {schema}.mark FOR UPDATE"
            let error = Assert.Catch(fun () -> waiting.ExecuteScalar() |> ignore)
            StringAssert.Contains("55P03", error.ToString())
    finally
        execute setup $"DROP SCHEMA IF EXISTS {schema} CASCADE"

[<Test; SqlCheck.NoSql>]
let ``FOR UPDATE refuses a query whose rows aren't a table's``() =
    let table = { Schema = "public"; Name = "mark"; Type = "" }
    let error =
        Assert.Throws<exn>(fun () ->
            SqlQuery.ofSqlExp(ForUpdate(Distinct(BaseTable("m", table))), Collections.Generic.List(), false) |> ignore)
    StringAssert.Contains("can't be distinct", error.Message)

// OnConflict.DoNothingOn and UpdateOn name the conflict's columns; a name the table hasn't is refused before any SQL.
[<Test; SqlCheck.NoSql>]
let ``a conflict on named columns does nothing or updates only the named columns``() =
    let cs = connectionString ()
    let provider = createProvider ()
    let schema = "sqlprovider_upsert_" + Guid.NewGuid().ToString("N").Substring(0, 8)
    use con = provider.CreateConnection cs
    con.Open()
    provider.CreateTypeMappings con
    let read () =
        if con.State <> ConnectionState.Open then con.Open()
        use cmd = con.CreateCommand()
        cmd.CommandText <- $"SELECT id || ' ' || name || ' ' || note FROM {schema}.mark ORDER BY id"
        use reader = cmd.ExecuteReader()
        [ while reader.Read() do reader.GetString 0 ]
    try
        execute con $"CREATE SCHEMA {schema}"
        execute con $"CREATE TABLE {schema}.mark (id int PRIMARY KEY, code text NOT NULL, name text NOT NULL, note text NOT NULL, UNIQUE (code))"
        execute con $"INSERT INTO {schema}.mark VALUES (1, 'a', 'first', 'kept')"
        let table = { Schema = schema; Name = "mark"; Type = "BASE TABLE" }
        let columns = provider.GetColumns(con, table)
        let insert (conflict: OnConflict) =
            let row = SqlEntity(Unchecked.defaultof<_>, Table.CreateFullName(schema, "mark"), columns, columns.Count)
            row.SetData [ "id", box 2; "code", box "a"; "name", box "second"; "note", box "changed" ]
            row._State <- Created
            row.OnConflict <- conflict
            let pending = Collections.Concurrent.ConcurrentDictionary<SqlEntity, DateTime>()
            pending.TryAdd(row, DateTime.UtcNow) |> ignore
            provider.ProcessUpdates(con, pending, Transactions.TransactionOptions.Default, None)
        insert (DoNothingOn [ "code" ])
        Assert.AreEqual([ "1 first kept" ], read ())
        insert (UpdateOn([ "CODE" ], [ Inserted "name" ]))
        Assert.AreEqual([ "1 second kept" ], read ())
        insert (UpdateOn([ "code" ], [ Constant("note", box "constant") ]))
        Assert.AreEqual([ "1 second constant" ], read ())
        let error = Assert.Throws<exn>(fun () -> insert (DoNothingOn [ "code) DO NOTHING; DROP TABLE mark; --" ]))
        StringAssert.Contains("isn't a column of", error.Message)
    finally
        execute con $"DROP SCHEMA IF EXISTS {schema} CASCADE"
